<?php

declare(strict_types=1);

namespace P13;

use Psr\Http\Message\UploadedFileInterface;

/**
 * Deterministic local file storage used for attachments (MAIL-05) and
 * import/export (MAIL-11). Files are stored under `storage/` and every
 * stored file keeps metadata linking it to its owner.
 */
final class Storage
{
    private string $root;

    public function __construct(private Database $db, private Config $config)
    {
        $this->root = (string) $config->get('storage.path');
        if (!is_dir($this->root)) {
            mkdir($this->root, 0777, true);
        }
        $userDir = $this->root . DIRECTORY_SEPARATOR . 'uploads';
        if (!is_dir($userDir)) {
            mkdir($userDir, 0777, true);
        }
    }

    /**
     * @return array{ok: bool, id?: int, file?: array<string, mixed>, error?: string}
     */
    public function storeUpload(UploadedFileInterface $upload, int $ownerId, string $purpose, ?int $messageId = null): array
    {
        $maxBytes = (int) $this->config->get('max_upload_mb', 10) * 1024 * 1024;

        if ($upload->getError() === UPLOAD_ERR_NO_FILE) {
            return ['ok' => false, 'error' => 'No file was uploaded.'];
        }
        if ($upload->getError() !== UPLOAD_ERR_OK) {
            return ['ok' => false, 'error' => 'File upload failed.'];
        }
        if ($upload->getSize() > $maxBytes) {
            return ['ok' => false, 'error' => 'File exceeds the maximum allowed size.'];
        }

        $originalName = (string) $upload->getClientFilename();
        $originalName = basename(str_replace('\\', '/', $originalName));
        $mime = (string) ($upload->getClientMediaType() ?: 'application/octet-stream');

        $allowed = ['text/plain', 'text/csv', 'application/pdf', 'application/json', 'text/html', 'image/png', 'image/jpeg', 'image/gif', 'application/octet-stream', 'application/x-pdf'];
        if (!in_array($mime, $allowed, true) && !str_ends_with($originalName, '.pdf')) {
            $baseMime = explode('/', $mime)[0] ?? '';
            if (!in_array($baseMime, ['text', 'image'], true) && $mime !== 'application/octet-stream') {
                return ['ok' => false, 'error' => 'File type is not allowed.'];
            }
        }

        $storedName = date('Ymd') . '_' . bin2hex(random_bytes(8)) . '_' . preg_replace('/[^A-Za-z0-9._-]/', '_', $originalName);
        $path = $this->root . DIRECTORY_SEPARATOR . 'uploads' . DIRECTORY_SEPARATOR . $storedName;
        $stream = $upload->getStream();
        $stream->rewind();
        if (file_put_contents($path, $stream->getContents()) === false) {
            return ['ok' => false, 'error' => 'Storage is unavailable.'];
        }

        $this->db->execute(
            'INSERT INTO stored_files (owner_user_id, message_id, purpose, original_name, stored_name, mime_type, size, created_at)
             VALUES (?, ?, ?, ?, ?, ?, ?, datetime(\'now\'))',
            [$ownerId, $messageId, $purpose, $originalName, $storedName, $mime, (int) $upload->getSize()]
        );
        $id = $this->db->lastInsertId();
        $file = $this->db->row('SELECT * FROM stored_files WHERE id = ?', [$id]);
        return ['ok' => true, 'id' => $id, 'file' => $file];
    }

    /**
     * Store a generated byte string (used for exports).
     *
     * @return array{ok: bool, id?: int, file?: array<string, mixed>, error?: string}
     */
    public function storeContent(string $content, int $ownerId, string $purpose, string $originalName, string $mime): array
    {
        $storedName = date('Ymd') . '_' . bin2hex(random_bytes(8)) . '_' . preg_replace('/[^A-Za-z0-9._-]/', '_', $originalName);
        $path = $this->root . DIRECTORY_SEPARATOR . 'uploads' . DIRECTORY_SEPARATOR . $storedName;
        if (file_put_contents($path, $content) === false) {
            return ['ok' => false, 'error' => 'Storage is unavailable.'];
        }
        $this->db->execute(
            'INSERT INTO stored_files (owner_user_id, message_id, purpose, original_name, stored_name, mime_type, size, created_at)
             VALUES (?, NULL, ?, ?, ?, ?, ?, datetime(\'now\'))',
            [$ownerId, $purpose, $originalName, $storedName, $mime, strlen($content)]
        );
        $id = $this->db->lastInsertId();
        $file = $this->db->row('SELECT * FROM stored_files WHERE id = ?', [$id]);
        return ['ok' => true, 'id' => $id, 'file' => $file];
    }

    /**
     * Absolute path of a stored file if it belongs to the given owner.
     */
    public function pathFor(int $fileId, int $ownerId): ?array
    {
        $file = $this->db->row(
            'SELECT * FROM stored_files WHERE id = ? AND owner_user_id = ?',
            [$fileId, $ownerId]
        );
        if ($file === null) {
            return null;
        }
        $path = $this->root . DIRECTORY_SEPARATOR . 'uploads' . DIRECTORY_SEPARATOR . $file['stored_name'];
        if (!is_file($path)) {
            return null;
        }
        return ['file' => $file, 'path' => $path];
    }

    public function absoluteUploadsPath(): string
    {
        return $this->root . DIRECTORY_SEPARATOR . 'uploads';
    }
}
